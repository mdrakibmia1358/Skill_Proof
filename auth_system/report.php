<?php
// report.php
// FR-8: PDF Report Generation
// Builds a PDF assessment report for one developer using FPDF (auth_system/vendor/fpdf.php)
// and logs the generation event in recruiter_reports (matches the RecruiterReport
// entity in the SRS domain class diagram).

session_start();
require_once __DIR__ . "/db_connect.php";

// 1. Only logged-in Recruiters may generate reports.
if (!isset($_SESSION["user_email"]) || ($_SESSION["user_role"] ?? "") !== "Recruiter") {
    header("Location: login.php");
    exit();
}

$developer_user_id = isset($_GET["user_id"]) ? (int) $_GET["user_id"] : 0;
if ($developer_user_id <= 0) {
    http_response_code(400);
    die("Invalid developer id.");
}

$pdo = skillproof_db();

// 2. Resolve the recruiter's own user_id (for the recruiter_reports log).
$recruiterStmt = $pdo->prepare("SELECT user_id FROM users WHERE email = ? LIMIT 1");
$recruiterStmt->execute([$_SESSION["user_email"]]);
$recruiterRow = $recruiterStmt->fetch();
$recruiter_id = $recruiterRow ? (int) $recruiterRow["user_id"] : null;

// 3. Load the developer and their latest analysis.
$devStmt = $pdo->prepare(
    "SELECT user_id, full_name, email, github_username, bio
     FROM users WHERE user_id = ? AND role = 'Developer' LIMIT 1"
);
$devStmt->execute([$developer_user_id]);
$developer = $devStmt->fetch();

if (!$developer) {
    http_response_code(404);
    die("Developer not found.");
}

$analysisStmt = $pdo->prepare(
    "SELECT * FROM skill_analyses WHERE user_id = ? ORDER BY analysis_id DESC LIMIT 1"
);
$analysisStmt->execute([$developer_user_id]);
$analysis = $analysisStmt->fetch();

$skills = [];
$dimensions = [];
$gaps = [];

if ($analysis) {
    $skillStmt = $pdo->prepare(
        "SELECT skill_name, score, level, evidence, status
         FROM skill_scores WHERE analysis_id = ? ORDER BY score DESC"
    );
    $skillStmt->execute([$analysis["analysis_id"]]);
    $skills = $skillStmt->fetchAll();

    $dimStmt = $pdo->prepare(
        "SELECT dimension_name, score, evidence
         FROM dimension_scores WHERE analysis_id = ? ORDER BY score DESC"
    );
    $dimStmt->execute([$analysis["analysis_id"]]);
    $dimensions = $dimStmt->fetchAll();

    $gapStmt = $pdo->prepare(
        "SELECT title, description, priority
         FROM learning_gaps WHERE analysis_id = ?"
    );
    $gapStmt->execute([$analysis["analysis_id"]]);
    $gaps = $gapStmt->fetchAll();
}

// 4. Log the report generation event.
if ($recruiter_id) {
    $logStmt = $pdo->prepare(
        "INSERT INTO recruiter_reports (recruiter_id, developer_id, analysis_id) VALUES (?, ?, ?)"
    );
    $logStmt->execute([$recruiter_id, $developer_user_id, $analysis["analysis_id"] ?? null]);
}

require_once __DIR__ . "/vendor/fpdf.php";

// FPDF's core fonts are Latin-1 only; convert UTF-8 DB text before printing.
function pdf_txt($value) {
    $value = (string) $value;
    $converted = @iconv("UTF-8", "ISO-8859-1//TRANSLIT", $value);
    return $converted !== false ? $converted : $value;
}

class SkillProofReportPDF extends FPDF {
    public $reportTitle = "Developer Assessment Report";

    function Header() {
        $this->SetFillColor(15, 23, 42); // slate-950
        $this->Rect(0, 0, 210, 22, "F");
        $this->SetTextColor(255, 255, 255);
        $this->SetFont("Helvetica", "B", 16);
        $this->SetXY(10, 6);
        $this->Cell(0, 10, "SkillProof - " . $this->reportTitle, 0, 1, "L");
        $this->SetTextColor(0, 0, 0);
        $this->Ln(10);
    }

    function Footer() {
        $this->SetY(-15);
        $this->SetFont("Helvetica", "I", 8);
        $this->SetTextColor(120, 120, 120);
        $this->Cell(0, 10, "Generated by SkillProof - Evidence-Based Developer Assessment Platform | Page " . $this->PageNo() . "/{nb}", 0, 0, "C");
    }

    function SectionTitle($text) {
        $this->SetFont("Helvetica", "B", 13);
        $this->SetTextColor(30, 41, 59);
        $this->Cell(0, 10, pdf_txt($text), 0, 1, "L");
        $this->SetDrawColor(220, 220, 220);
        $this->Line($this->GetX(), $this->GetY(), 200, $this->GetY());
        $this->Ln(4);
    }

    function ScoreBar($label, $score) {
        $score = max(0, min(100, (int) $score));
        $this->SetFont("Helvetica", "", 10);
        $this->SetTextColor(50, 50, 50);
        $this->Cell(60, 6, pdf_txt($label), 0, 0, "L");

        $barX = $this->GetX();
        $barY = $this->GetY() + 1;
        $barWidth = 90;

        $this->SetFillColor(226, 232, 240); // slate-200 track
        $this->Rect($barX, $barY, $barWidth, 4, "F");

        $this->SetFillColor(37, 99, 235); // blue-600 fill
        $this->Rect($barX, $barY, $barWidth * ($score / 100), 4, "F");

        $this->SetXY($barX + $barWidth + 4, $this->GetY());
        $this->Cell(20, 6, $score . "%", 0, 1, "L");
    }
}

$pdf = new SkillProofReportPDF();
$pdf->AliasNbPages();
$pdf->AddPage();

// --- Developer summary block ---
$pdf->SetFont("Helvetica", "B", 18);
$pdf->SetTextColor(15, 23, 42);
$pdf->Cell(0, 10, pdf_txt($developer["full_name"]), 0, 1, "L");

$pdf->SetFont("Helvetica", "", 11);
$pdf->SetTextColor(80, 80, 80);
$pdf->Cell(0, 7, pdf_txt("Email: " . $developer["email"]), 0, 1, "L");
$analyzedGithub = $analysis["github_username"] ?? null;
$registeredGithub = $developer["github_username"] ?? null;

if ($analyzedGithub) {
    $pdf->Cell(0, 7, pdf_txt("GitHub (analyzed): " . $analyzedGithub), 0, 1, "L");
    if ($registeredGithub && $registeredGithub !== $analyzedGithub) {
        $pdf->SetTextColor(180, 100, 0);
        $pdf->Cell(0, 6, pdf_txt("Note: registered account is \"" . $registeredGithub . "\" - scores reflect a different GitHub account."), 0, 1, "L");
        $pdf->SetTextColor(80, 80, 80);
    }
} else {
    $pdf->Cell(0, 7, pdf_txt("GitHub: " . ($registeredGithub ?: "Not connected")), 0, 1, "L");
}
if (!empty($developer["bio"])) {
    $pdf->MultiCell(0, 6, pdf_txt("Bio: " . $developer["bio"]));
}
$pdf->Ln(4);

if (!$analysis) {
    $pdf->SetFont("Helvetica", "I", 11);
    $pdf->SetTextColor(150, 0, 0);
    $pdf->MultiCell(0, 8, "This developer has not connected a GitHub account or run an analysis yet. No verified evidence is available.");
} else {
    // --- Trust / Career scores ---
    $pdf->SectionTitle("Overall Scores");
    $pdf->ScoreBar("Developer Trust Score", $analysis["trust_score"]);
    $pdf->ScoreBar("Career Readiness", $analysis["career_score"]);
    $pdf->Ln(4);

    $pdf->SetFont("Helvetica", "", 10);
    $pdf->SetTextColor(80, 80, 80);
    $pdf->Cell(0, 6, pdf_txt(
        "Repositories analyzed: " . $analysis["total_repositories"] .
        " | Stars: " . $analysis["total_stars"] .
        " | Languages: " . $analysis["languages_detected"] .
        " | Last analyzed: " . $analysis["analyzed_at"]
    ), 0, 1, "L");
    $pdf->Ln(6);

    // --- Skill table ---
    $pdf->SectionTitle("Verified Skills");
    $pdf->SetFont("Helvetica", "B", 9);
    $pdf->SetFillColor(241, 245, 249);
    $pdf->Cell(50, 8, "Skill", 1, 0, "L", true);
    $pdf->Cell(20, 8, "Score", 1, 0, "C", true);
    $pdf->Cell(30, 8, "Level", 1, 0, "C", true);
    $pdf->Cell(30, 8, "Status", 1, 0, "C", true);
    $pdf->Cell(60, 8, "Evidence", 1, 1, "L", true);

    $pdf->SetFont("Helvetica", "", 8);
    foreach ($skills as $skill) {
        if (($skill["score"] ?? 0) <= 0) continue;
        $pdf->Cell(50, 7, pdf_txt($skill["skill_name"]), 1, 0, "L");
        $pdf->Cell(20, 7, $skill["score"] . "%", 1, 0, "C");
        $pdf->Cell(30, 7, pdf_txt($skill["level"]), 1, 0, "C");
        $pdf->Cell(30, 7, pdf_txt($skill["status"]), 1, 0, "C");
        $evidence = pdf_txt($skill["evidence"]);
        if (strlen($evidence) > 55) $evidence = substr($evidence, 0, 52) . "...";
        $pdf->Cell(60, 7, $evidence, 1, 1, "L");
    }
    $pdf->Ln(6);

    // --- Dimension scores ---
    $pdf->SectionTitle("Assessment Dimensions");
    foreach ($dimensions as $dimension) {
        $pdf->ScoreBar($dimension["dimension_name"], $dimension["score"]);
    }
    $pdf->Ln(4);

    // --- Learning gaps ---
    if (!empty($gaps)) {
        $pdf->SectionTitle("Learning Gaps & Recommendations");
        $pdf->SetFont("Helvetica", "", 9);
        foreach ($gaps as $gap) {
            $pdf->SetFont("Helvetica", "B", 9);
            $pdf->Cell(0, 6, pdf_txt("[" . $gap["priority"] . "] " . $gap["title"]), 0, 1, "L");
            $pdf->SetFont("Helvetica", "", 9);
            $pdf->MultiCell(0, 5, pdf_txt($gap["description"]));
            $pdf->Ln(2);
        }
    }
}

$pdf->Ln(6);
$pdf->SetFont("Helvetica", "I", 8);
$pdf->SetTextColor(140, 140, 140);
$pdf->MultiCell(0, 5, "This report reflects publicly available GitHub evidence at the time of analysis. Scores are generated algorithmically by the SkillProof Analysis Engine and do not constitute a guarantee of skill level.");

$safeName = preg_replace("/[^a-zA-Z0-9_-]/", "_", $developer["full_name"]);
$pdf->Output("D", "SkillProof_Report_" . $safeName . ".pdf");
exit();